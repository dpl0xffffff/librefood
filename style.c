/* A broken rule silently drops styling; surface it instead. */
static void on_css_error(GtkCssProvider *p, GtkCssSection *section,
                         const GError *error, gpointer user_data) {
    (void)p; (void)user_data;
    char *where = gtk_css_section_to_string(section);
    g_warning("librefood: CSS error at %s: %s", where, error->message);
    g_free(where);
}

void apply_css(void) {
    GtkCssProvider *provider = gtk_css_provider_new();
    g_signal_connect(provider, "parsing-error", G_CALLBACK(on_css_error), NULL);
    /* App providers don't follow the desktop light/dark preference on their
     * own; without this the @media (prefers-color-scheme) block never applies. */
    g_object_bind_property(gtk_settings_get_default(), "gtk-interface-color-scheme",
                           provider, "prefers-color-scheme", G_BINDING_SYNC_CREATE);
    gtk_css_provider_load_from_string(provider, APP_CSS);
    gtk_style_context_add_provider_for_display(
        gdk_display_get_default(),
        GTK_STYLE_PROVIDER(provider),
        GTK_STYLE_PROVIDER_PRIORITY_APPLICATION
    );
    g_object_unref(provider);
}
